export type WeightedMessage = { text: string; weight: number };

export function pickRandomMessage(messages: readonly WeightedMessage[]): string {
  const totalWeight = messages.reduce((total, message) => total + Math.max(0, message.weight), 0);
  if (totalWeight <= 0) return messages[0]?.text ?? '';

  let choice = Math.random() * totalWeight;
  for (const message of messages) {
    choice -= Math.max(0, message.weight);
    if (choice < 0) return message.text;
  }
  return messages[messages.length - 1].text;
}
