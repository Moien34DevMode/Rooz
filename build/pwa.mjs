import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

async function filesIn(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => {
    const name = `${prefix}${entry.name}`;
    return entry.isDirectory() ? filesIn(join(directory, entry.name), `${name}/`) : [name];
  }));
  return files.flat();
}

export function serviceWorkerSource(files, version) {
  return `// Generated by Rooz's PWA build. Do not edit.
const VERSION = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const SCOPE = new URL(self.registration.scope);
// Include scope in the namespace so multiple deployments on one origin coexist.
const CACHE_PREFIX = 'rooz-shell:' + encodeURIComponent(SCOPE.href) + ':';
const CACHE_NAME = CACHE_PREFIX + VERSION;
const PRECACHE_URLS = FILES.map(file => new URL(file, SCOPE).href);
const PRECACHE = new Set(PRECACHE_URLS);
const INDEX_URL = new URL('index.html', SCOPE).href;
const NAVIGATION_TIMEOUT_MS = 3000;
const PRECACHE_TIMEOUT_MS = 30000;

function inScope(url) {
  return url.origin === SCOPE.origin && url.pathname.startsWith(SCOPE.pathname);
}

function goodResponse(response) {
  return response.ok && response.status !== 206 &&
    response.type !== 'opaque' && response.type !== 'opaqueredirect' &&
    !response.redirected;
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    // Fetch everything before writing: a failed download must fail installation.
    const responses = await Promise.all(PRECACHE_URLS.map(async url => {
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), PRECACHE_TIMEOUT_MS);
      try {
        const response = await fetch(new Request(url, {
          cache: 'reload', redirect: 'error', signal: controller.signal
        }));
        if (!goodResponse(response)) throw new Error('Cannot precache ' + url);
        // Drain each body now to release HTTP/1 connections for queued downloads.
        const body = await response.arrayBuffer();
        return new Response(response.status === 204 || response.status === 205 ? null : body, {
          status: response.status, statusText: response.statusText, headers: response.headers
        });
      } catch (error) {
        controller.abort();
        throw error;
      } finally {
        // The deadline covers headers AND body consumption, not just fetch().
        clearTimeout(timer);
      }
    }));
    const cache = await caches.open(CACHE_NAME);
    try {
      for (let i = 0; i < PRECACHE_URLS.length; i++) {
        await cache.put(PRECACHE_URLS[i], responses[i]);
      }
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
    // No skipWaiting: an open planner must keep its current worker and assets.
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map(name => caches.delete(name)));
    // No clients.claim: do not take over an existing, unsaved planner session.
  })());
});

async function navigation(request) {
  let timer;
  try {
    const response = await Promise.race([
      fetch(request),
      new Promise((_, reject) => {
        timer = setTimeout(() => reject(new Error('Navigation timeout')), NAVIGATION_TIMEOUT_MS);
      })
    ]);
    if (goodResponse(response)) return response;
  } catch {
    // Offline, server errors and stalled requests all use the installed shell.
  } finally {
    clearTimeout(timer);
  }
  const cache = await caches.open(CACHE_NAME);
  return await cache.match(INDEX_URL) || new Response('Rooz is unavailable offline.', {
    status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' }
  });
}

async function shellAsset(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request.url);
  if (cached) return cached;
  // Never runtime-cache responses: only the validated installation owns this cache.
  try {
    return await fetch(request);
  } catch {
    return new Response('Rooz asset unavailable.', { status: 503 });
  }
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || !inScope(url)) return;
  if (request.mode === 'navigate') {
    event.respondWith(navigation(request));
  } else if (PRECACHE.has(url.href)) {
    event.respondWith(shellAsset(request));
  }
});
`;
}

/** @returns {import('vite').Plugin} */
export function pwaBuild() {
  /** @type {import('vite').ResolvedConfig} */
  let config;
  return {
    name: 'rooz-pwa-build',
    apply: 'build',
    enforce: 'post',
    configResolved(resolved) { config = resolved; },
    async writeBundle() {
      const outDir = resolve(config.root, config.build.outDir);
      // Inspect the written output, not just Rollup's bundle: public files matter too.
      const files = (await filesIn(outDir))
        .filter(file => file !== 'sw.js' && !file.endsWith('.map'))
        .sort();
      if (!files.includes('index.html') || !files.includes('manifest.webmanifest')) {
        throw new Error('Rooz PWA requires index.html and manifest.webmanifest in the build output.');
      }
      const hash = createHash('sha256');
      for (const file of files) {
        const bytes = await readFile(join(outDir, file));
        hash.update(JSON.stringify([file, bytes.length]));
        hash.update(bytes);
      }
      await writeFile(join(outDir, 'sw.js'), serviceWorkerSource(files, hash.digest('hex')), 'utf8');
    }
  };
}
